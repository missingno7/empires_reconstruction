static void test_rle_control_zero_one_repeat(void)
{
    static const uint8_t in[2] = { 0x00, 0xAB };
    static const uint8_t expect[1] = { 0xAB };
    uint8_t out[8];
    dos_uint n;

    memset(out, 0, sizeof out);
    n = rle_packbits_decode(in, out, sizeof in);
    check_len("rle_control_zero", n, sizeof expect);
    check_bytes("rle_control_zero", out, expect, sizeof expect);
}

static void test_rle_control_0x80_129_repeats(void)
{
    static const uint8_t in[2] = { 0x80, 0xCD };
    uint8_t out[130];
    dos_uint n, i;

    memset(out, 0, sizeof out);
    n = rle_packbits_decode(in, out, sizeof in);
    check_len("rle_control_0x80", n, 129);
    for (i = 0; i < 129 && i < n; i++) {
        if (out[i] != 0xCD) {
            fail("rle_control_0x80", "expected all 129 bytes to be 0xCD");
            break;
        }
    }
}

