/* test_decode.c -- hand-authored vectors for the four asm/DECODE.ASM
 * transcriptions in portable/resource/decode.c.  No test framework: prints
 * failures and returns nonzero.  Does not touch assets/, so it never
 * skips (no SKIP_RETURN_CODE 77 path here).
 *
 * The RLE vectors are cross-checked against tools/resource_codecs.py's
 * unpack_rle(); the LZ vectors are real pack_pair_span() output from that
 * same validated module, so decoding them exercises literal codes,
 * back-references (pair-spans) and the 9->10 bit width growth against an
 * independently-produced bitstream, not just our own encoder-of-the-day.
 */
#include "decode.h"

#include <stdio.h>
#include <string.h>

static int g_failures = 0;

static void fail(const char *test, const char *what)
{
    fprintf(stderr, "test_decode: %s: %s\n", test, what);
    g_failures++;
}

static void check_len(const char *test, dos_uint got, dos_uint expect)
{
    if (got != expect) {
        fprintf(stderr, "test_decode: %s: length mismatch: got %u, expected %u\n",
                test, (unsigned)got, (unsigned)expect);
        g_failures++;
    }
}

static void check_bytes(const char *test, const uint8_t *got, const uint8_t *expect, size_t n)
{
    size_t i;
    for (i = 0; i < n; i++) {
        if (got[i] != expect[i]) {
            fprintf(stderr, "test_decode: %s: byte %zu mismatch: got 0x%02x, expected 0x%02x\n",
                    test, i, got[i], expect[i]);
            g_failures++;
            return; /* one report per test is enough */
        }
    }
}

